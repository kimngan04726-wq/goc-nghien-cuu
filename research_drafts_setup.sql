create unique index if not exists research_drafts_cell_slot_unique on public.research_drafts(cell_id,slot);
create table if not exists public.research_draft_versions (
 id bigint generated by default as identity primary key,
 draft_id bigint not null references public.research_drafts(id) on delete cascade,
 content_html text not null default '',
 content_text text not null default '',
 word_count integer not null default 0 check(word_count>=0),
 saved_by uuid references auth.users(id),
 saved_at timestamptz not null default now(),
 kind text not null check(kind in ('manual','auto','restore')),
 note text not null default ''
);
create index if not exists idx_research_drafts_cell on public.research_drafts(cell_id);
create index if not exists idx_research_draft_versions_latest on public.research_draft_versions(draft_id,saved_at desc,id desc);
create index if not exists idx_research_draft_versions_auto on public.research_draft_versions(draft_id,saved_by,saved_at desc) where kind='auto';
create or replace function public.research_draft_is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where user_id=auth.uid() and role='admin')
$$;
create or replace function public.research_draft_is_member(p_cell bigint) returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where user_id=auth.uid() and role='member')
 and exists(select 1 from public.research_page_assignments where user_id=auth.uid() and page_id=p_cell)
$$;
create or replace function public.research_draft_can_write(p_cell bigint,p_slot text,p_owner uuid) returns boolean language sql stable security definer set search_path=public as $$
 select public.research_draft_is_admin() or (
   public.research_draft_is_member(p_cell) and (
      p_slot='summary' or (p_slot in ('draft1','draft2') and p_owner=auth.uid())
   )
 )
$$;
alter table public.research_drafts enable row level security;
alter table public.research_draft_versions enable row level security;
drop policy if exists "drafts read" on public.research_drafts;
create policy "drafts read" on public.research_drafts for select to authenticated using (true);
drop policy if exists "drafts insert" on public.research_drafts;
create policy "drafts insert" on public.research_drafts for insert to authenticated with check(public.research_draft_can_write(cell_id,slot,owner_id));
drop policy if exists "drafts update" on public.research_drafts;
create policy "drafts update" on public.research_drafts for update to authenticated using(public.research_draft_can_write(cell_id,slot,owner_id)) with check(public.research_draft_can_write(cell_id,slot,owner_id));
drop policy if exists "versions read" on public.research_draft_versions;
create policy "versions read" on public.research_draft_versions for select to authenticated using(exists(select 1 from public.research_drafts d where d.id=draft_id));
drop policy if exists "versions insert" on public.research_draft_versions;
create policy "versions insert" on public.research_draft_versions for insert to authenticated with check(saved_by=auth.uid() and exists(select 1 from public.research_drafts d where d.id=draft_id and public.research_draft_can_write(d.cell_id,d.slot,d.owner_id)));
drop policy if exists "versions update auto" on public.research_draft_versions;
create policy "versions update auto" on public.research_draft_versions for update to authenticated using(kind='auto' and saved_by=auth.uid() and saved_at>now()-interval '10 minutes' and exists(select 1 from public.research_drafts d where d.id=draft_id and public.research_draft_can_write(d.cell_id,d.slot,d.owner_id))) with check(kind='auto' and saved_by=auth.uid());
drop policy if exists "versions delete auto" on public.research_draft_versions;
create policy "versions delete auto" on public.research_draft_versions for delete to authenticated using(kind='auto' and exists(select 1 from public.research_drafts d where d.id=draft_id and public.research_draft_can_write(d.cell_id,d.slot,d.owner_id)));
grant select,insert,update on public.research_drafts to authenticated;
grant select,insert,update,delete on public.research_draft_versions to authenticated;
grant usage,select on all sequences in schema public to authenticated;
