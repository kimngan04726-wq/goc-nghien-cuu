-- Safe additive installation. Does NOT alter existing research_drafts,
-- whose primary key is (page_id, slot) and slot is integer (1 or 2).
-- Run in Supabase SQL Editor after reviewing role/assignment mapping.
begin;
create table if not exists public.research_editor_drafts (
 id bigint generated by default as identity primary key,
 cell_id bigint not null references public.research_pages(id) on delete cascade,
 slot text not null check (slot in ('draft1','draft2','summary')),
 owner_id uuid references auth.users(id),
 content_html text not null default '',
 content_text text not null default '',
 word_count integer not null default 0 check(word_count>=0),
 status text not null default 'Đang viết',
 updated_at timestamptz not null default now(),
 unique(cell_id,slot)
);
create table if not exists public.research_editor_draft_versions (
 id bigint generated by default as identity primary key,
 draft_id bigint not null references public.research_editor_drafts(id) on delete cascade,
 content_html text not null default '',
 content_text text not null default '',
 word_count integer not null default 0 check(word_count>=0),
 saved_by uuid references auth.users(id),
 saved_at timestamptz not null default now(),
 kind text not null check(kind in ('manual','auto','restore')),
 note text not null default ''
);
create index if not exists research_editor_versions_latest on public.research_editor_draft_versions(draft_id,saved_at desc,id desc);
create index if not exists research_editor_versions_auto on public.research_editor_draft_versions(draft_id,saved_by,saved_at desc) where kind='auto';
create or replace function public.research_editor_is_admin()
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.group_profiles where user_id=auth.uid() and role='admin')
$$;
create or replace function public.research_editor_is_member(p_cell bigint)
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.group_profiles where user_id=auth.uid() and role='member')
 and exists(select 1 from public.research_page_assignments where user_id=auth.uid() and page_id=p_cell)
$$;
create or replace function public.research_editor_can_write(p_cell bigint,p_slot text,p_owner uuid)
returns boolean language sql stable security definer set search_path=public as $$
 select public.research_editor_is_admin() or
 (public.research_editor_is_member(p_cell) and
 (p_slot='summary' or (p_slot in ('draft1','draft2') and p_owner=auth.uid())))
$$;
alter table public.research_editor_drafts enable row level security;
alter table public.research_editor_draft_versions enable row level security;
drop policy if exists "editor drafts read" on public.research_editor_drafts;
create policy "editor drafts read" on public.research_editor_drafts for select to authenticated using(true);
drop policy if exists "editor drafts insert" on public.research_editor_drafts;
create policy "editor drafts insert" on public.research_editor_drafts for insert to authenticated
with check(public.research_editor_can_write(cell_id,slot,owner_id));
drop policy if exists "editor drafts update" on public.research_editor_drafts;
create policy "editor drafts update" on public.research_editor_drafts for update to authenticated
using(public.research_editor_can_write(cell_id,slot,owner_id))
with check(public.research_editor_can_write(cell_id,slot,owner_id));
drop policy if exists "editor versions read" on public.research_editor_draft_versions;
create policy "editor versions read" on public.research_editor_draft_versions for select to authenticated
using(exists(select 1 from public.research_editor_drafts d where d.id=draft_id));
drop policy if exists "editor versions insert" on public.research_editor_draft_versions;
create policy "editor versions insert" on public.research_editor_draft_versions for insert to authenticated
with check(saved_by=auth.uid() and exists(select 1 from public.research_editor_drafts d
 where d.id=draft_id and public.research_editor_can_write(d.cell_id,d.slot,d.owner_id)));
drop policy if exists "editor versions update auto" on public.research_editor_draft_versions;
create policy "editor versions update auto" on public.research_editor_draft_versions for update to authenticated
using(kind='auto' and saved_by=auth.uid() and saved_at>now()-interval '10 minutes'
 and exists(select 1 from public.research_editor_drafts d where d.id=draft_id
 and public.research_editor_can_write(d.cell_id,d.slot,d.owner_id)))
with check(kind='auto' and saved_by=auth.uid());
drop policy if exists "editor versions delete auto" on public.research_editor_draft_versions;
create policy "editor versions delete auto" on public.research_editor_draft_versions for delete to authenticated
using(kind='auto' and exists(select 1 from public.research_editor_drafts d where d.id=draft_id
 and public.research_editor_can_write(d.cell_id,d.slot,d.owner_id)));
grant select,insert,update on public.research_editor_drafts to authenticated;
grant select,insert,update,delete on public.research_editor_draft_versions to authenticated;
grant usage,select on sequence public.research_editor_drafts_id_seq to authenticated;
grant usage,select on sequence public.research_editor_draft_versions_id_seq to authenticated;
commit;
-- Legacy research_drafts remains untouched; no old draft is deleted.
-- Existing drafts are NOT automatically migrated into the new editor tables.
-- Admin must assign owner_id to draft1/draft2 for member editing.
