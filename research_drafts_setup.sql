-- Existing source of cell IDs: public.research_pages.id.
-- Existing authorization: public.profiles(role,user_id), public.research_page_assignments(page_id,user_id).
-- Existing website already uses research_drafts(page_id,slot,content,author_id). Preserve those columns.
create table if not exists public.research_drafts (
 id bigint generated by default as identity primary key,
 cell_id bigint not null references public.research_pages(id) on delete cascade,
 slot text not null check (slot in ('draft1','draft2','summary')),
 owner_id uuid references auth.users(id),
 content_html text not null default '',
 content_text text not null default '',
 word_count integer not null default 0 check (word_count >= 0),
 status text not null default 'Đang viết',
 updated_at timestamptz not null default now(),
 unique(cell_id,slot)
);
